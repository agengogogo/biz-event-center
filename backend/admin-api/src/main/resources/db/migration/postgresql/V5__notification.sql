-- Notification channels, templates and delivery tracking.

CREATE TABLE notification_channel (
    id         varchar(64) PRIMARY KEY,
    name       varchar(128) NOT NULL,
    type       varchar(32) NOT NULL,
    park_id    varchar(64) NOT NULL,
    config     text,
    enabled    boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_notification_channel_park ON notification_channel (park_id, enabled);

CREATE TABLE notification_template (
    id           varchar(64) PRIMARY KEY,
    name         varchar(128) NOT NULL,
    channel_type varchar(32),
    subject      varchar(512),
    body         text NOT NULL,
    park_id      varchar(64) NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_notification_template_park ON notification_template (park_id);

CREATE TABLE notification_delivery (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    park_id          varchar(64) NOT NULL,
    event_id         varchar(64) NOT NULL,
    subscription_id  varchar(64),
    channel_id       varchar(64),
    status           varchar(16) NOT NULL,
    error            varchar(2048),
    rendered_content text,
    attempts         integer NOT NULL DEFAULT 0,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_notification_delivery_park_time ON notification_delivery (park_id, created_at DESC);
CREATE INDEX idx_notification_delivery_event ON notification_delivery (event_id);
